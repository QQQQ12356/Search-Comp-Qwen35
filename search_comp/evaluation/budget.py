"""交互式评测的生成预算：与 Search-R1 训练轨迹的分布对齐。

训练轨迹里每条 assistant 输出是一段 ``think + <search>`` 或 ``think + <answer>``。
实测 800 条轨迹的 token 分布：

===========  =====  =====  =====  ======
assistant 段  p50    p90    p99    max
===========  =====  =====  =====  ======
首轮（搜索）   151    275    488    2146
末轮（回答）   161    277    580    1284
===========  =====  =====  =====  ======

轮数分布（5000 条轨迹的 assistant 消息数）为 ``2: 2822 / 3: 1986 / 4: 192``，即最多
**3 次 search + 1 次 answer**。

评测若沿用更小的预算（例如 256 token / 3 轮），模型会在吐出 ``</search>`` 或
``</answer>`` 之前被截断：约 12%~14% 的题在结构上不可能答对，3 次搜索的轨迹也拿不到
回答轮。本模块是 beacon / plain / native 三条评测路径共用的默认值，避免各自漂移。
"""

from __future__ import annotations

#: 每轮生成上限（覆盖训练分布 p99≈580，留出余量）。
#: 上限本身不产生额外开销：命中 ``</search>`` / ``</answer>`` 即停，只有模型本来就会
#: 生成更长的样本才用得上，所以取值偏向覆盖长尾而非省时间。
MAX_NEW_TOKENS_PER_TURN = 768

#: 最大轮数（训练轨迹最多 3 次 search + 1 次 answer）。
MAX_TURNS = 4
